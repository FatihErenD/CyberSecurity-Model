PREVIOUS_MODEL_PATH = fenrir_config.get("PREVIOUS_MODEL_PATH")
OUTPUT_DIR = fenrir_config.get("OUTPUT_DIR")
FINAL_SAVE_PATH = os.path.join(OUTPUT_DIR, "fenrir-qwen-final")

DATASET_NAME = "AlicanKiraz0/Cybersecurity-Dataset-Fenrir-v2.1"
MAX_SEQ_LENGTH = 2048

BATCH_SIZE = 64
GRAD_ACCUMULATION = 1
EPOCHS = 1  # Overfit'i önlemek için 10'dan 3'e düşürüldü
LEARNING_RATE = 1e-5
LOGGING_STEPS = 20
SAVE_STEPS = 100

